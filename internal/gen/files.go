package gen

import (
	"fmt"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// ---------- file generators ----------

func (g *generator) fileHeader(what, src string) string {
	return fmt.Sprintf(`// Code generated by cmd/kodi-gen from %s. DO NOT EDIT.

package %s
`, src, g.pkg) + what
}

// genClient emits the versioned Client wrapper embedding the shared transport.
func (g *generator) genClient() (string, error) {
	parts := strings.SplitN(g.version, ".", 3)
	if len(parts) < 2 {
		return "", fmt.Errorf("invalid schema version %q", g.version)
	}
	major, err := strconv.Atoi(parts[0])
	if err != nil {
		return "", fmt.Errorf("invalid schema version %q", g.version)
	}
	minor, err := strconv.Atoi(parts[1])
	if err != nil {
		return "", fmt.Errorf("invalid schema version %q", g.version)
	}
	var b strings.Builder
	b.WriteString(g.fileHeader(fmt.Sprintf("// Schema version %s.\n\n", g.version),
		filepath.Join(g.schemaDir, "types.json")))
	fmt.Fprintf(&b, "import %q\n\n", g.rpcImport)
	fmt.Fprintf(&b, `// APIMajor is the major Kodi JSON-RPC API version this package speaks.
// It is bumped on backwards incompatible changes to the API definition.
const APIMajor = %d

// APIMinor is the minor Kodi JSON-RPC API version this package was generated from.
// It is bumped on backwards compatible additions to the API definition.
const APIMinor = %d

// Client is a JSON-RPC client for Kodi API v%d (schema version %s).
// The transport is shared with all API versions; see the rpc package.
type Client struct {
	*rpc.Client
}

// NewClient creates a Client targeting endpoint (e.g. "http://localhost:8080/jsonrpc").
func NewClient(endpoint string, opts ...rpc.Option) *Client {
	return &Client{Client: rpc.NewClient(endpoint, opts...)}
}

// Wrap adapts an existing shared transport client (e.g. after version
// negotiation) to this API version.
func Wrap(c *rpc.Client) *Client {
	return &Client{Client: c}
}

// Compile-time guarantee that the versioned client satisfies rpc.Caller,
// so it works with version-agnostic helpers (negotiation, …).
var _ rpc.Caller = (*Client)(nil)
`, major, minor, major, g.version)
	return b.String(), nil
}

func (g *generator) genTypes() (string, error) {
	var b strings.Builder
	b.WriteString(g.fileHeader(fmt.Sprintf("// Schema version %s.\n\n", g.version), filepath.Join(g.schemaDir, "types.json")))
	fmt.Fprintf(&b, "// SchemaVersion is the Kodi JSON-RPC schema version (schema/version.txt)\n// this package was generated from.\nconst SchemaVersion = %q\n\n", g.version)
	for _, name := range g.typeOrder {
		src := g.defineTopLevel(name, decodeNode(g.typeRaw[name]))
		if src != "" {
			b.WriteString(src)
			b.WriteString("\n")
		}
	}
	// Flush any nested declarations created while resolving types.
	b.WriteString(g.extraDefsFlush())
	// Stubs for unresolved refs (sorted for determinism).
	if len(g.missing) > 0 {
		var names []string
		for n := range g.missing {
			names = append(names, n)
		}
		sort.Strings(names)
		b.WriteString("// Unresolved references (not present in schema/types.json).\n")
		for _, n := range names {
			if !g.defined[typeName(n)] {
				g.defined[typeName(n)] = true
				b.WriteString(g.defineStub(n))
				b.WriteString("\n")
			}
		}
	}
	return b.String(), nil
}
